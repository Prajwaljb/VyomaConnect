L['pc', 'tiny'] = root('tiny', ring('82', 42, 12), pad=5, gravity='center')
L['pc', 'small'] = root('small', ring('82', 38, 11) + gap(8) + col(text('My PC', 13, bold=True) + online()), pad=7)
L['pc', 'wide_small'] = root('wide_small', ring('82', 38, 11) + gap(8) + col(text('My PC', 13, bold=True) + online())
    + icon('ic_w_phone', 14, SOFT) + gap(3) + reading('64', 13, bolt=True), pad=7)
L['pc', 'medium'] = root('medium', text('My PC', 14, bold=True) + online() + FLEX_V
    + row(ring('82', 56, 16), gravity='center') + FLEX_V
    + row(icon('ic_w_phone', 12, SOFT) + gap(3) + reading('64', 12, bolt=True), gravity='center'),
    orient='vertical', gravity='top', pad=10)
def hrow(body):
    return '<LinearLayout android:layout_width="wrap_content" android:layout_height="wrap_content" android:gravity="center_vertical">\n%s</LinearLayout>\n' % body
def battery(label, glyph, v, bolt=False):
    return col(hrow(ring(v, 52, 12, glyph) + gap(8) + col(text(label, 10, SOFT) + hrow(reading(v, 18, bolt)), weight=False)), weight=True)
L['pc', 'large'] = root('large', text('My PC', 15, bold=True) + online(11) + FLEX_V
    + row(battery('PC', 'ic_w_laptop', '82') + battery('Phone', 'ic_w_phone', '64', bolt=True)),
    orient='vertical', gravity='top')

# ---- shortcuts: Home's tiles
TILES = [('ic_w_upload', 'Send files', 'blue'), ('ic_w_clipboard', 'Send clip', 'teal'), ('ic_w_mouse', 'Touchpad', 'orange'),
         ('ic_play', 'Play', 'pink'), ('ic_w_lock', 'Lock PC', 'mint'), ('ic_w_mute', 'Mute', 'gray')]
def tile(i, labelled, last=False, h='match_parent'):
    ic, label, hue = TILES[i]
    margin = '' if last else ' android:layout_marginEnd="6dp"'
    if labelled:
        return ('<LinearLayout android:layout_width="0dp" android:layout_weight="1" android:layout_height="%s" android:orientation="vertical" '
                'android:background="@drawable/widget_pv_tile_%s" android:padding="7dp"%s>\n%s%s%s</LinearLayout>\n') % (
            h, hue, margin, icon(ic, 16, WHITE), FLEX_V, text(label, 9, WHITE))
    return ('<FrameLayout android:layout_width="0dp" android:layout_weight="1" android:layout_height="%s" android:background="@drawable/widget_pv_tile_%s"%s>\n'
            '<ImageView android:layout_width="18dp" android:layout_height="18dp" android:layout_gravity="center" android:src="@drawable/%s" android:tint="%s" />\n</FrameLayout>\n') % (
        h, hue, margin, ic, WHITE)
def tiles(idx, labelled):
    return ''.join(tile(i, labelled, k == len(idx) - 1) for k, i in enumerate(idx))
GRID_ROW = lambda body, top=False: row(body, height='0dp', extra=' android:layout_weight="1"' + ('' if top else ' android:layout_marginTop="6dp"'))
L['shortcuts', 'tiny'] = root('tiny', icon('ic_w_upload', 24, WHITE), pad=0, gravity='center', bg='@drawable/widget_pv_whole_blue')
L['shortcuts', 'small'] = root('small', row(tiles([0, 1], False), height='match_parent'), pad=6)
L['shortcuts', 'wide_small'] = root('wide_small', row(tiles([0, 1, 2, 3, 4], False), height='match_parent'), pad=6)
L['shortcuts', 'medium'] = root('medium', GRID_ROW(tiles([0, 1], False), True) + GRID_ROW(tiles([2, 3], False)), orient='vertical', pad=7)
L['shortcuts', 'large'] = root('large', GRID_ROW(tiles([0, 1, 2], True), True) + GRID_ROW(tiles([3, 4, 5], True)), orient='vertical', pad=7)

# ---- now playing: the media card
CARD = '@drawable/widget_pv_card'
def cover(size):
    return '<FrameLayout android:layout_width="%ddp" android:layout_height="%ddp" android:background="@drawable/widget_pv_cover" />\n' % (size, size)
def play(size, glyph='ic_pause'):
    return ('<ImageView android:layout_width="%ddp" android:layout_height="%ddp" android:background="@drawable/widget_pv_play" '
            'android:padding="%ddp" android:src="@drawable/%s" android:tint="#FF1C1C1E" />\n') % (size, size, round(size * 0.25), glyph)
def controls(size):
    return icon('ic_skip_previous', round(size * 0.6), WHITE) + gap(10) + play(size) + gap(10) + icon('ic_skip_next', round(size * 0.6), WHITE)
SONG = lambda sp: text('Song title', sp, WHITE, True)

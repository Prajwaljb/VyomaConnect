# Usage: python3 scripts/gen_widget_previews.py app/src/main/res
# Writes One UI's per-size widget-picker previews (tiny 1x1, small 2x1, wideSmall 4x1, medium 2x2,
# large 4x2; canvas sizes from SESL) as app/src/main/res/layout/widget_preview_<widget>_<size>.xml,
# and the few drawables they need (drawable/widget_pv_*.xml). Static stand-ins for the Glance widgets
# in widget/WidgetViews.kt: same layout and colours, sample content. Re-run after changing a widget.
import colorsys, glob, os, sys

RES = sys.argv[1]
A = 'xmlns:android="http://schemas.android.com/apk/res/android"'
SIZES = {'tiny': (52, 52), 'small': (125, 52), 'wide_small': (270, 52), 'medium': (125, 130), 'large': (270, 130)}
INK, SOFT, WHITE = '@color/widget_ink', '@color/widget_ink_soft', '@android:color/white'
GREEN = '#FF30D158'

# The app's system colours (light), as solid tiles: mid tones drop to 38% lightness (WidgetViews Hue.fill).
HUES = {'blue': 0x007AFF, 'teal': 0x30B0C7, 'orange': 0xFF9500, 'pink': 0xFF2D55, 'mint': 0x00C7BE, 'gray': 0x8E8E93}

def lum(rgb):
    def ch(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)

def fill(rgb):
    if lum(rgb) < 0.2:
        return '#FF%06X' % rgb
    r, g, b = ((rgb >> 16) & 255) / 255, ((rgb >> 8) & 255) / 255, (rgb & 255) / 255
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    l = min(l, 0.38)
    while True:  # white keeps 3.5:1 or more (mint sits at 39% already)
        r2, g2, b2 = colorsys.hls_to_rgb(h, l, s)
        out = (round(r2 * 255) << 16) | (round(g2 * 255) << 8) | round(b2 * 255)
        if lum(out) <= 0.25 or l <= 0.1:
            return '#FF%06X' % out
        l -= 0.02

def drawable(name, body):
    open(os.path.join(RES, 'drawable', name + '.xml'), 'w').write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/gen_widget_previews.py -->\n' + body)

for f in glob.glob(os.path.join(RES, 'drawable', 'widget_pv_*.xml')):
    os.remove(f)
for name, rgb in HUES.items():
    drawable('widget_pv_tile_' + name, '<shape %s android:shape="rectangle">\n    <corners android:radius="12dp" />\n    <solid android:color="%s" />\n</shape>\n' % (A, fill(rgb)))
for name in ('blue', 'teal'):  # whole-widget tiles: Shortcuts' and Clipboard's 1x1
    rgb = HUES[name]
    drawable('widget_pv_whole_' + name, '<shape %s android:shape="rectangle">\n    <corners android:radius="@android:dimen/system_app_widget_background_radius" />\n    <solid android:color="%s" />\n</shape>\n' % (A, fill(rgb)))
drawable('widget_pv_capsule', '<shape %s android:shape="rectangle">\n    <corners android:radius="14dp" />\n    <solid android:color="%s" />\n</shape>\n' % (A, fill(HUES['teal'])))
drawable('widget_pv_ring', '<layer-list %s>\n    <item><shape android:shape="ring" android:useLevel="false" android:innerRadiusRatio="2.6" android:thicknessRatio="11"><solid android:color="#1F000000" /></shape></item>\n'
         '    <item><shape android:shape="ring" android:useLevel="false" android:innerRadiusRatio="2.6" android:thicknessRatio="11"><solid android:color="%s" /></shape></item>\n</layer-list>\n' % (A, GREEN))
drawable('widget_pv_play', '<shape %s android:shape="oval">\n    <solid android:color="#FFFFFFFF" />\n</shape>\n' % A)
# The media card: a deep sea blue (the sample cover's palette), the cover a sunset fading into it.
drawable('widget_pv_card', '<shape %s android:shape="rectangle">\n    <corners android:radius="@android:dimen/system_app_widget_background_radius" />\n    <solid android:color="#FF102A3A" />\n</shape>\n' % A)
drawable('widget_pv_cover', '<shape %s android:shape="rectangle">\n    <corners android:radius="10dp" />\n    <gradient android:angle="270" android:startColor="#FFFF8A3D" android:centerColor="#FFFFC46B" android:endColor="#FF1F4E6B" />\n</shape>\n' % A)

def root(size, body, orient='horizontal', pad=12, bg='@drawable/widget_preview_bg', gravity='center_vertical'):
    w, h = SIZES[size]
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/gen_widget_previews.py (One UI %s slot). Static sample content. -->\n'
            '<LinearLayout %s\n    android:id="@android:id/background"\n'
            '    android:layout_width="%ddp" android:layout_height="%ddp"\n'
            '    android:background="%s" android:orientation="%s" android:gravity="%s" android:padding="%ddp">\n%s</LinearLayout>\n'
            ) % (size, A, w, h, bg, orient, gravity, pad, body)

def text(t, sp, color=INK, bold=False, extra=''):
    return ('<TextView android:layout_width="wrap_content" android:layout_height="wrap_content" android:text="%s" '
            'android:textColor="%s" android:textSize="%ssp"%s android:maxLines="1" android:ellipsize="end"%s />\n'
            ) % (t, color, sp, ' android:textStyle="bold"' if bold else '', extra)

def col(body, weight=True, gravity=None, extra=''):
    w = 'android:layout_width="0dp" android:layout_weight="1"' if weight else 'android:layout_width="wrap_content"'
    g = ' android:gravity="%s"' % gravity if gravity else ''
    return '<LinearLayout %s android:layout_height="wrap_content" android:orientation="vertical"%s%s>\n%s</LinearLayout>\n' % (w, g, extra, body)

def row(body, gravity='center_vertical', extra='', height='wrap_content'):
    return '<LinearLayout android:layout_width="match_parent" android:layout_height="%s" android:gravity="%s"%s>\n%s</LinearLayout>\n' % (height, gravity, extra, body)

def gap(w=0, h=0):
    return '<FrameLayout android:layout_width="%ddp" android:layout_height="%ddp" />\n' % (w or 1, h or 1)

FLEX_V = '<FrameLayout android:layout_width="1dp" android:layout_height="0dp" android:layout_weight="1" />\n'

def icon(name, size, tint=INK):
    return '<ImageView android:layout_width="%ddp" android:layout_height="%ddp" android:src="@drawable/%s" android:tint="%s" />\n' % (size, size, name, tint)

def badge(name, hue, size):
    return ('<ImageView android:layout_width="%ddp" android:layout_height="%ddp" android:background="@drawable/widget_pv_tile_%s" '
            'android:padding="%ddp" android:src="@drawable/%s" android:tint="%s" />\n') % (size, size, hue, round(size * 0.21), name, WHITE)

def ring(label, size, sp, glyph=None):
    if glyph:
        return ('<ImageView android:layout_width="%ddp" android:layout_height="%ddp" android:background="@drawable/widget_pv_ring" '
                'android:padding="%ddp" android:src="@drawable/%s" android:tint="%s" />\n') % (size, size, round(size * 0.3), glyph, INK)
    return ('<TextView android:layout_width="%ddp" android:layout_height="%ddp" android:gravity="center" android:background="@drawable/widget_pv_ring" '
            'android:text="%s" android:textColor="%s" android:textSize="%ssp" android:textStyle="bold" />\n') % (size, size, label, INK, sp)

def online(sp=10):
    return text('● Connected', sp, '@color/widget_online')

def reading(v, sp, bolt=False):
    return (text(v, sp, bold=True) + text('%', round(sp * 0.6), SOFT)
            + (icon('ic_w_bolt', round(sp * 0.85), GREEN) if bolt else ''))

L = {}
